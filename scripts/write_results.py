"""Render the results tables (results_main.md) from runs/analysis/results.json and
runs/alignment/summary.json. Every frozen test is listed, supported or not; missing inputs are
shown as 'not run' rather than dropped.

Usage:  python -m scripts.write_results --analysis runs/analysis/results.json \
            --alignment runs/alignment/summary.json --out results_main.md
"""

import argparse
import json
import os


def f(x, d=3):
    return "-" if x is None else (f"{x:.{d}f}" if isinstance(x, (int, float)) else str(x))


def ci(c, d=3):
    return "-" if not c else f"[{f(c[0], d)}, {f(c[1], d)}]"


def verdict(r):
    if r.get("missing"):
        return "not run"
    if "supported" in r:
        return "**supported**" if r["supported"] else ("opposite direction" if r.get("opposite") else "not supported")
    return r.get("verdict", "-")


def test_rows(fam, label):
    L = [f"| {label} | mean | 95% BCa CI | p | Holm p | sign test (+/n) | n seeds | verdict |",
         "|---|---|---|---|---|---|---|---|"]
    for k, r in fam.items():
        if not isinstance(r, dict):
            continue
        if r.get("missing"):
            L.append(f"| {k} | - | - | - | - | - | - | not run |")
            continue
        sg = r.get("sign", {})
        L.append(f"| {k} | {f(r.get('mean'))} | {ci(r.get('ci95_bca'))} | {f(r.get('p'), 4)} | "
                 f"{f(r.get('p_holm'), 4)} | {sg.get('n_pos', '-')}/{sg.get('n_nonzero', '-')} | "
                 f"{r.get('n', '-')} | {verdict(r)} |")
    return L


def render(R, S):
    L = ["# Main results: Blind to the Missing Term", "",
         f"Seeds {R['seeds'][0]}-{R['seeds'][-1]} ({len(R['seeds'])}), {R['n_boot']} bootstrap resamples. "
         "Rules: prereg-v1 section 8, addenda v1.1-v1.6, section 11 entries of 2026-11-20. "
         "Generated by `scripts/write_results.py`; do not edit by hand.", ""]
    rc = R["r_reuse_check"]
    L += [f"Surrogate check (Family A vs RQ1 at eps = 0): {rc['cells_checked']} cells, largest relative "
          f"difference {rc['max_rel_diff']:.1e}.", ""]

    B = R["family_B"]
    L += ["## Family B: ranking (Holm over 4)", ""] + test_rows(
        {k: v for k, v in B.items() if k.startswith("B1")}, "B1 slope of AUROC on log r") + [""]
    L += ["| B2 | log r½(RQ1) - log r½(RQ2) | 90% CI | TOST p | Holm p | verdict |", "|---|---|---|---|---|---|"]
    for k in ("B2_S1", "B2_S2"):
        r = B.get(k, {"missing": True})
        L.append(f"| {k} | {f(r.get('diff_log_rhalf'))} | {ci(r.get('ci90'))} | {f(r.get('p'), 4)} | "
                 f"{f(r.get('p_holm'), 4)} | {verdict(r)}{' (' + r['reason'] + ')' if r.get('reason') else ''} |")
    L += ["", "## Family A: acquisition (Holm over 6)", ""] + test_rows(R["family_A"], "test") + [""]
    L += ["## Family C (C1, arm 8 r-gated)", ""] + test_rows(R["family_C"], "test") + [""]
    for k, r in R["family_C"].items():
        if r.get("best_fixed_arm"):
            L.append(f"{k}: best fixed arm by mean regret = {r['best_fixed_arm']}.")
    F = R["family_F"]
    L += ["", "## Family F: acquisition for a learned term (Holm over 4)", ""]
    L += test_rows({k: v for k, v in F.items() if k != "stop_rule"}, "test") if F else ["Not run yet."]
    if F.get("stop_rule"):
        L += ["", f"Stop rule: {F['stop_rule']}."]

    L += ["", "## P-A: predicted vs observed transition (n_nom = 512, seven levels)", "",
          "| System | signal | observed r½ | 90% CI | predicted r½ (plug-in) | inside CI | within 1.5x | "
          "success | Gaussian variant r½ / success |", "|---|---|---|---|---|---|---|---|---|"]
    for s, v in R["P_A"].items():
        for sig, x in v.items():
            if x.get("missing"):
                L.append(f"| {s} | {sig} | not run | | | | | | |")
                continue
            p, g = x.get("pred_empirical", {}), x.get("pred_gaussian", {})
            L.append(f"| {s} | {sig}{' (primary)' if sig == 'ens_sigma' else ''} | {f(x['fit'].get('r_half'))} | "
                     f"{ci(x.get('ci90_r_half'))} | {f(p.get('r_half'))} | {p.get('inside_ci', '-')} | "
                     f"{p.get('within_1_5', '-')} | **{p.get('success', '-')}** | "
                     f"{f(g.get('r_half'))} / {g.get('success', '-')} |")

    L += ["", "## P-C: blindness horizon (secondary)", "", "| System | level | predicted t* | observed t* |",
          "|---|---|---|---|"]
    for s, v in R["P_C"].items():
        if v.get("missing"):
            continue
        for m, h in v["observed_horizon"].items():
            L.append(f"| {s} | {m} x | {v.get('predicted_horizon', {}).get(m, '-')} | {h} |")
        L.append(f"| {s} | **result** | | {'not applicable (section 11)' if s == 'S1' else v.get('success')} "
                 f"({v.get('levels_equal_or_adjacent')} of 4 equal or adjacent) |")

    D = R["D"]
    L += ["", "## D-tests (v1.5, secondary)", "", "| test | statistic | result |", "|---|---|---|"]
    for s in ("S1", "S2"):
        d1 = D.get(f"D1_{s}")
        if d1:
            L.append(f"| D1 {s} (TOST, margin 0.10) | mean rho(E) - rho(D) = {f(d1['mean'])}, p = {f(d1['p'], 4)} | "
                     f"{'equivalent' if d1['equivalent'] else 'not equivalent'} |")
        d2 = D.get(f"D2_{s}")
        if d2:
            L.append(f"| D2 {s} (sign {'+' if d2['predicted_sign'] > 0 else '-'}) | slope {f(d2['mean'])}, "
                     f"CI {ci(d2['ci95_bca'])}, p = {f(d2['p'], 4)} | {'success' if d2['success'] else 'not met'} |")
        d3 = D.get(f"D3_{s}")
        if d3:
            x = d3["32"]
            L.append(f"| D3 {s} at n = 32 (pred. {d3['prediction']}) | aligned in {x['aligned']} of {x['n_seeds']}, "
                     f"CI {ci(x['ci95'], 2)} | {d3['success']} |")

    L += ["", "## Alignment range (v1.6, secondary)", ""]
    if not S:
        L.append("Not run yet.")
    else:
        L += ["| System | criterion | count | required | met | note |", "|---|---|---|---|---|---|"]
        for s, o in S.items():
            for k, v in o.items():
                if isinstance(v, dict) and "k" in v:
                    note = f"max gap {f(v['max_gap'])}" if "max_gap" in v else f"95% CI {ci(v['ci95'], 2)}"
                    L.append(f"| {s} | {k} | {v['k']}/{v['n']} | {v['required']} | **{v['met']}** | {note} |")
            for sig in ("ens_sigma", "ode_resid"):
                c, w = o.get(f"R1c_{sig}"), o.get(f"R2_{sig}")
                if c:
                    L.append(f"| {s} | R1c_{sig} (descriptive) | range {c['inside_range']}/{c['n']}, "
                             f"band {c['inside_band']}/{c['n']} | - | - | |")
                if w:
                    L.append(f"| {s} | R2_{sig} (descriptive) | width {f(w['width_full_mean'], 2)} full, "
                             f"{f(w['width_reduced_mean'], 2)} reduced | - | - | |")
    L += ["", "Collapse across n_nom and D4 tables: see `runs/analysis/results.json` (descriptive)."]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", default=os.path.join("runs", "analysis", "results.json"))
    ap.add_argument("--alignment", default=os.path.join("runs", "alignment", "summary.json"))
    ap.add_argument("--out", default="results_main.md")
    a = ap.parse_args()
    R = json.load(open(a.analysis, encoding="utf-8"))
    S = json.load(open(a.alignment, encoding="utf-8")) if os.path.exists(a.alignment) else None
    open(a.out, "w", encoding="utf-8").write(render(R, S))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
